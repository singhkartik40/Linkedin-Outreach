import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import http from 'node:http';
test('local API guards, import lifecycle, key redaction, and sending gate', async () => {
  const dir = mkdtempSync(path.join(tmpdir(), 'outreach-api-'));
  const port = 14318, base = `http://127.0.0.1:${port}`;
  const child = spawn(process.execPath, ['server/index.mjs'], { env: { ...process.env, PORT: String(port), DATA_DIR: dir }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
  try {
    await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('Server did not start')), 10000);
      child.stdout.on('data', () => { clearTimeout(timer); resolve(); });
      child.on('error', reject);
      child.on('exit', code => { clearTimeout(timer); reject(new Error(`Server exited ${code}`)); });
    });
    const post = (route, data, origin = base) => fetch(`${base}/api${route}`, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify(data) });
    assert.equal((await post('/automation', {}, 'https://evil.example')).status, 403);
    const badHostStatus = await new Promise((resolve, reject) => { const request = http.get(`${base}/api/state`, { headers: { Host: 'evil.example' } }, response => { response.resume(); resolve(response.statusCode); }); request.on('error', reject); });
    assert.equal(badHostStatus, 403);
    const malformedStatus = await new Promise((resolve, reject) => {
      const request = http.get({ hostname: '127.0.0.1', port, path: 'http://[' }, response => { response.resume(); resolve(response.statusCode); });
      request.on('error', reject);
    });
    assert.equal(malformedStatus, 400);
    assert.equal((await fetch(`${base}/api/state`)).status, 200, 'malformed URLs must not crash the server');
    assert.equal((await post('/settings/provider', { provider: 'openai', model: 'test-model', apiKey: 'PRIVATE_TEST_KEY' })).status, 200);
    const stateResponse = await fetch(`${base}/api/state`), stateText = await stateResponse.text();
    assert.ok(!stateText.includes('PRIVATE_TEST_KEY')); assert.equal(JSON.parse(stateText).provider.hasKey, true);
    const job = { url: 'https://example.com/jobs/1?utm_source=test', text: 'Example company is hiring a Product Designer in Bengaluru.', mode: 'manual' };
    assert.equal((await post('/jobs', job)).status, 201);
    assert.equal((await post('/jobs', { ...job, url: 'https://example.com/jobs/1' })).status, 409);
    assert.equal((await post('/jobs/discovered', { jobs: [{ url: 'https://www.linkedin.com/jobs/view/1234567890/', title: 'UX Designer', company: 'Fresh Co', location: 'India', recency: '1 hour ago', source: 'UX Designer Fresh Co India 1 hour ago' }] })).status, 200);
    const state = await (await fetch(`${base}/api/state`)).json();
    assert.equal(state.jobs[0].assessment.status, 'To verify');
    assert.equal(state.jobs[0].facts.company.value, 'Fresh Co');
    const originalJob = state.jobs.find(item => item.url === 'https://example.com/jobs/1');
    assert.equal((await post('/jobs/' + originalJob.id + '/facts', { facts: { company: { value: 'Example', evidence: 'Example company' } } })).status, 200);
    const recentJobs = [{ url: 'https://www.linkedin.com/jobs/view/1234567890/', title: 'UX Designer', company: 'Fresh Co', location: 'India', recency: '1 hour ago' }];
    const people = [{ name: 'Asha Rao', headline: 'Recruiter at Fresh Co', location: 'Bengaluru', degree: '2', company: 'Fresh Co', jobUrl: recentJobs[0].url, profileUrl: 'https://www.linkedin.com/in/asha-rao/?trk=search' }];
    assert.equal((await post('/people/import', { people, jobs: [{ ...recentJobs[0], recency: '3 days ago' }], replace: false })).status, 400);
    assert.equal((await post('/people/import', { people: [{ ...people[0], jobUrl: 'https://www.linkedin.com/jobs/view/999/' }], jobs: recentJobs, replace: false })).status, 400);
    assert.equal((await post('/people/import', { people: [{ ...people[0], company: 'Unrelated Co' }], jobs: recentJobs, replace: false })).status, 400);
    assert.equal((await post('/people/import', { people, jobs: recentJobs, replace: false })).status, 200);
    const peopleState = await (await fetch(`${base}/api/state`)).json();
    assert.equal(peopleState.contacts.length, 1); assert.equal(peopleState.contacts[0].name, 'Asha Rao'); assert.ok(peopleState.contacts[0].message.length <= 290);
    assert.equal((await post('/people/import', { people, jobs: recentJobs, replace: false })).status, 200);
    assert.equal((await (await fetch(`${base}/api/state`)).json()).contacts.length, 1);
    const contactId = peopleState.contacts[0].id;
    assert.ok(peopleState.contacts[0].message.includes('https://karteek.work'));
    assert.ok(peopleState.contacts[0].message.includes('16hilLHZ3_4nvYX56vPKkKpMFjUqpk1oN/view?usp=sharing'));
    assert.equal((await post(`/contacts/${contactId}`, { message: 'x'.repeat(291) })).status, 400);
    assert.equal((await (await fetch(`${base}/api/state`)).json()).contacts[0].message, peopleState.contacts[0].message);
    assert.equal((await post(`/contacts/${contactId}/done`, {})).status, 200);
    const doneState = await (await fetch(`${base}/api/state`)).json();
    assert.equal(doneState.contacts[0].status, 'Send confirmed');
    assert.equal(doneState.contacts[0].sheetSyncStatus, 'Awaiting Sheet update');
    assert.ok(doneState.contacts[0].confirmedAt);
    assert.equal((await post('/people/import', { people, jobs: recentJobs, replace: true })).status, 200);
    const retry = await (await post(`/contacts/${contactId}/sync-sheet`, {})).json();
    assert.equal(retry.sheetUpdated, false);
    assert.match(retry.error, /not configured/i);
    assert.equal((await (await fetch(`${base}/api/state`)).json()).contacts[0].status, 'Send confirmed');
    assert.equal((await post('/automation', { autoSync: true, desiredSending: 'automatic' })).status, 200);
    assert.equal((await post('/send', {})).status, 409);
    assert.equal((await post('/tracker/configure', { spreadsheetId: 'bad' })).status, 400);
    assert.equal((await post('/tracker/writer/configure', { url: 'https://evil.example/write', token: 'test-token-with-at-least-thirty-two-characters' })).status, 400);
    assert.equal((await post('/tracker/writer/configure', { url: 'https://script.google.com/macros/s/TEST_DEPLOYMENT/exec', token: 'test-token-with-at-least-thirty-two-characters' })).status, 200);
    const writerState = await (await fetch(`${base}/api/state`)).text();
    assert.equal(JSON.parse(writerState).google.writeConfigured, true);
    assert.ok(!writerState.includes('test-token-with-at-least-thirty-two-characters'));
    const founder = { ...people[0], name: 'Founder Example', headline: 'Cofounder at Fresh Co', location: 'Indore, India', profileUrl: 'https://www.linkedin.com/in/founder-example/' };
    const founderImport = await (await post('/people/import', { people: [founder], jobs: recentJobs, mode: 'all' })).json();
    assert.equal(founderImport.added, 1, 'a founder outside the metro list needs no funding report');
    assert.equal(founderImport.addedFounders, 1);
    const savedFounder = (await (await fetch(`${base}/api/state`)).json()).contacts.find(contact => contact.name === founder.name);
    assert.equal(savedFounder.funding, null);
    assert.match(savedFounder.message, /pitch/);
    assert.doesNotMatch(savedFounder.message, /funding|refer me/);
  } finally {
    child.kill();
    await new Promise(resolve => child.exitCode !== null ? resolve() : child.once('exit', resolve));
    rmSync(dir, { recursive: true, force: true });
  }
});
